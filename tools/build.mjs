import { readdir, readFile, mkdir, rm, stat, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const runtime=['index.html','style.css','manifest.webmanifest','sw.js','js','assets'];
const marker='.mermaid-build';

async function listFiles(relative){
  const source=path.join(root,relative);
  if((await stat(source)).isFile())return [relative];
  const entries=await readdir(source,{withFileTypes:true});
  const lists=await Promise.all(entries.filter(e=>e.isFile()||e.isDirectory()).map(e=>listFiles(path.join(relative,e.name))));
  return lists.flat().sort();
}

export async function build(destination=path.join(root,'dist')){
  const files=(await Promise.all(runtime.map(listFiles))).flat().sort();
  const sources=await Promise.all(files.map(async file=>({file,bytes:await readFile(path.join(root,file))})));
  const hash=createHash('sha256');
  for(const {file,bytes} of sources){hash.update(file.replaceAll('\\','/'));hash.update('\0');hash.update(bytes);}
  const revision=hash.digest('hex').slice(0,16);
  const sw=sources.find(s=>s.file==='sw.js');
  if(!/const CACHE='[^']+';/.test(sw.bytes.toString()))throw new Error('Service-worker cache declaration was not found.');
  // Never delete an unknown folder: only replace our own generated output.
  try{
    await stat(destination);
    await stat(path.join(destination,marker));
    await rm(destination,{recursive:true});
  }catch(error){
    if(error.code!=='ENOENT')throw error;
    try{await stat(destination);throw new Error(`Refusing to overwrite an unmarked directory: ${destination}`);}catch(check){if(check.code!=='ENOENT')throw check;}
  }
  await mkdir(destination,{recursive:true});
  await writeFile(path.join(destination,marker),'Generated by Mermaid Slither. Safe to replace using npm run build.\n');
  for(const {file,bytes} of sources){
    const output=path.join(destination,file);await mkdir(path.dirname(output),{recursive:true});
    const body=file==='sw.js'?bytes.toString().replace(/const CACHE='[^']+';/,`const CACHE='mermaid-slither-${revision}';`):bytes;
    await writeFile(output,body);
  }
  await writeFile(path.join(destination,'.nojekyll'),'');
  return {destination,revision,files:files.map(f=>f.replaceAll('\\','/'))};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const result=await build();
  console.log(`Packaged ${result.files.length} runtime files into dist/ (offline revision ${result.revision}).`);
}
